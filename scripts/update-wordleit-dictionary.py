#!/usr/bin/env python3
"""Rebuild WordleIt's five-letter dictionary from a verified Morph-it! release."""
import hashlib
import io
from pathlib import Path
import re
import tarfile
import subprocess

ROOT = Path(__file__).resolve().parents[1]
URL = 'https://docs.sslmit.unibo.it/lib/exe/fetch.php?media=resources:morph-it.tgz'
SHA256 = 'b137343dc095e038ebfaef7c743185e85ec35f5322a1b8629b600e6e898c7024'
data = subprocess.run(["curl", "--fail", "--silent", "--show-error", "--location", "--max-time", "60", URL], check=True, capture_output=True).stdout
if hashlib.sha256(data).hexdigest() != SHA256:
    raise SystemExit('Upstream archive changed. Review the release before updating the checksum.')
with tarfile.open(fileobj=io.BytesIO(data), mode='r:gz') as archive:
    lexicon = archive.extractfile('current_version/morph-it_048.txt').read().decode('iso-8859-1')
    words = set()
    for line in lexicon.splitlines():
        fields = line.split('\t')
        if len(fields) != 3:
            continue
        word, lemma, tag = fields
        # Exclude proper nouns, abbreviations, accents, punctuation and non-five-letter forms.
        if re.fullmatch('[a-z]{5}', word) and not tag.startswith(('NPR', 'ABR')):
            words.add(word.upper())
    target = ROOT / 'src/lib/wordleit/dictionary.ts'
    target.write_text('// Generated by scripts/update-wordleit-dictionary.py. Do not edit.\n'
                      '// Derived from Morph-it! 0.4.8, Marco Baroni and Eros Zanchetta.\n'
                      '// CC BY-SA 2.0; see public/wordleit/dictionary/README.md.\n'
                      'export const DICTIONARY_WORDS = `' + ' '.join(sorted(words)) + '`.split(" ");\n')
    notices = ROOT / 'public/wordleit/dictionary'
    notices.mkdir(parents=True, exist_ok=True)
    (notices / 'morph-it-readme.txt').write_bytes(archive.extractfile('current_version/readme-morph-it.txt').read())
print(f'Generated {len(words)} five-letter words.')
